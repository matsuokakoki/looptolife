const languageSelect = document.getElementById("language-select");
const originalText = new Map();
const normalizedTranslations = new Map(
  Object.entries(laoTranslations).map(([english, lao]) => [english.trim().replace(/\s+/g, " "), lao])
);

function setLanguage(language) {
  document.documentElement.lang = language;
  document.querySelectorAll("body *:not(script):not(style)").forEach((element) => {
    if (element.children.length || element.closest(".language-switcher")) return;
    if (!originalText.has(element)) originalText.set(element, element.textContent);
    const english = originalText.get(element);
    const key = english.trim().replace(/\s+/g, " ");
    const translation = language === "lo" ? normalizedTranslations.get(key) : null;
    if (translation) element.textContent = translation;
    else if (language === "en") element.textContent = english;
  });
  try { localStorage.setItem("looptolife-language", language); } catch {}
}

languageSelect.addEventListener("change", (event) => setLanguage(event.target.value));
try {
  const savedLanguage = localStorage.getItem("looptolife-language");
  if (savedLanguage === "lo") {
    languageSelect.value = "lo";
    setLanguage("lo");
  }
} catch {}
